def tls_check(op):
 import base64,tempfile
 checks={}
 for item in json.loads(op.k('get','secrets','-o','json'))['items']:
  data=item.get('data',{});name=item['metadata']['name']
  if 'tls.crt' not in data:continue
  with tempfile.TemporaryDirectory() as directory:
   root=Path(directory);crt=root/'leaf';ca=root/'ca';crt.write_bytes(base64.b64decode(data['tls.crt']));ca.write_bytes(base64.b64decode(data['ca.crt']))
   role=name.removesuffix('-tls-auth');host=role+'.'+op.namespace+'.svc.cluster.local'
   subprocess.run(['openssl','verify','-CAfile',str(ca),'-verify_hostname',host,str(crt)],capture_output=True,check=True)
   subprocess.run(['openssl','x509','-in',str(crt),'-checkend','3600','-noout'],capture_output=True,check=True)
   checks[name]=dict(certificate_sha256=sha(crt),ca_sha256=sha(ca),hostname=host)
 return checks

