  # Query accounting through the model owner's own pod before shutdown. Failed
  # observations remain unknown; no inferred zero or refunded reservations.
  try:report['accounting']=json.loads(exec_code(op,'fusion-model',"import json;from integration.single_node.future_live import projection;print(json.dumps(projection('/campaign/plan.json','/run/fusion/owner.json')))"))
  except Exception as e:report['accounting']=dict(status='UNKNOWN',reason=str(e)[-300:])
  accounting=report['accounting']
  if 'spent' in accounting:
   ledger.update(reservations=len(accounting['spent']),captures=len(accounting['captured']),backend_calls=accounting['backend_calls'],live_generations=accounting['backend_calls'],slots={s['name']:('CAPTURED' if s['id'] in accounting['captured'] else 'SPENT_UNKNOWN' if s['id'] in accounting['spent'] else 'UNRESERVED') for s in plan['slots']})
   report.update(backend_calls=accounting['backend_calls'],provider_usage=accounting['provider_usage'])
  else:
   ledger.update(reservations='UNKNOWN',captures='UNKNOWN',backend_calls='UNKNOWN',live_generations='UNKNOWN',slots={s['name']:'UNKNOWN' for s in plan['slots']})
  cleanup=[]
  for role in ('omega-agent','fusion-channel-bridge','irc-peer','fusion-model'):
   try:op.k('scale','statefulset',role,'--replicas=0');cleanup.append(dict(role=role,stop='requested'))
   except Exception as e:cleanup.append(dict(role=role,stop='UNKNOWN',error=str(e)[-300:]))
  try:op.k('wait','--for=delete','pod/fusion-model-0','--timeout=45s',timeout=50);report['runtime_stopped']=True
  except Exception as e:report['runtime_stopped']='UNKNOWN';report['cleanup_error']=str(e)[-300:]
  report['cleanup']=cleanup
  ledger.update(state='STOPPED_REVIEW_REQUIRED',result_sha256=digest(canonical(report)),finished_ms=time.time_ns()//1000000);write(ledgerpath,ledger);write(root/'execution-report.json',report)
